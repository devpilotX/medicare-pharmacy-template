window.t = function (key) {
  const d = window.I18N[window.LANG] || window.I18N.en;
  return d[key] != null ? d[key] : (window.I18N.en[key] != null ? window.I18N.en[key] : key);
};
window.LANG = (function () {
  try { return localStorage.getItem('medicare:lang') || (navigator.language && navigator.language.startsWith('hi') ? 'hi' : 'en'); } catch (e) { return 'en'; }
})();
window.applyI18n = function (root) {
  (root || document).querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (key) el.textContent = window.t(key);
  });
  (root || document).querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (key) el.setAttribute('placeholder', window.t(key));
  });
  document.documentElement.setAttribute('lang', window.LANG);
};
window.setLang = function (lang) {
  window.LANG = lang;
  try { localStorage.setItem('medicare:lang', lang); } catch (e) {}
  location.reload();
};
